#define _POSIX_C_SOURCE 200809L
#include "modprobe_gen.h"
#include <errno.h>
#include <fcntl.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

/* Clean up the temp file and return -1 with `err` restored as errno (the
 * cleanup unlink/fclose would otherwise clobber the meaningful errno). */
static int fail_cleanup(const char *tmp, int err) {
    unlink(tmp);
    errno = err;
    return -1;
}

int modprobe_gen_lr2021(const Settings *s, const char *path) {
    char tmp[512];
    if (snprintf(tmp, sizeof tmp, "%s.tmpXXXXXX", path) >= (int)sizeof tmp) {
        errno = ENAMETOOLONG;
        return -1;
    }
    int fd = mkstemp(tmp);
    if (fd < 0) return -1;
    /* mkstemp creates 0600; modprobe.d conf files are conventionally 0644 (the
     * file is non-secret module params, and the agent reads it back). */
    if (fchmod(fd, 0644) != 0) { int e = errno; close(fd); return fail_cleanup(tmp, e); }
    FILE *f = fdopen(fd, "w");
    if (!f) { int e = errno; close(fd); return fail_cleanup(tmp, e); }

    fprintf(f, "# /etc/modprobe.d/lr2021.conf -- generated by pivid-config-agent.\n");
    fprintf(f, "# Boot defaults for the LR2021 FLRC layer. Outer framing is always\n");
    fprintf(f, "# DYNAMIC (variable-length); there is no flrc_mode knob.\n");
    fprintf(f, "options lr2021 flrc_cr=%d flrc_crc_width=%d "
               "flrc_preamble_len=%d flrc_sync_len=%d flrc_pld_len=%d "
               "flrc_tx_low_thresh=%d rx_boost=%d rf_freq_hz=%llu rf_tx_power_dbm=%d\n",
            s->flrc_cr, s->flrc_crc_width, s->flrc_preamble_len,
            s->flrc_sync_len, s->flrc_pld_len, s->flrc_tx_low_thresh,
            s->rx_boost, (unsigned long long)s->rf_frequency, s->rf_tx_power);

    if (fflush(f) != 0 || fsync(fileno(f)) != 0) { int e = errno; fclose(f); return fail_cleanup(tmp, e); }
    if (fclose(f) != 0) { return fail_cleanup(tmp, errno); }
    if (rename(tmp, path) != 0) { return fail_cleanup(tmp, errno); }
    return 0;
}
