#!/usr/bin/env bash
#
# pivid-config-net.sh up|down — config-mode network orchestration.
#
# §4.4 resolved on hardware 2026-06-15: this DietPi image runs ifupdown +
# wpa_supplicant (no NetworkManager / nmcli), so we ship our own hostapd +
# dnsmasq. The WiFi client is declarative (/etc/network/interfaces +
# wpa_supplicant.conf), brought up at boot/hotplug by ifup@wlan0.service.
#
#   up   : stop + MASK the boot/hotplug client (so a wlan0 udev event can't
#          re-grab the radio), bring wlan0 up as an open AP (PiVid-TX/-RX) on
#          static 10.0.0.1, start hostapd + dnsmasq, and confirm hostapd reaches
#          AP-ENABLED (retried). HW-RCA 2026-06-24: without this fence the client
#          re-associated on top of the AP and hostapd stalled in COUNTRY_UPDATE.
#   down : clear the /run/pivid/config-mode flag (so the LED goes dark at once),
#          stop hostapd + dnsmasq, unmask + restore the WiFi client. (The unit's
#          ExecStartPost creates the flag on enter; ExecStopPost is a backstop.)
#
# Self-stranding guard: if the AP fails to come up, roll back to client mode so
# a headless box is never left off the network. A reboot also restores the
# client (none of the config-mode units are enabled).
#
# Testability: external commands are invoked by bare name (PATH-resolved) and
# paths/role are env-overridable, so tests/test_config_net.sh runs it against
# stubs. NOT `set -e`: teardown is best-effort.

set -uo pipefail

WLAN_IF="${PIVID_WLAN_IF:-wlan0}"
AP_ADDR="${PIVID_AP_ADDR:-10.0.0.1}"
AP_CIDR="${AP_ADDR}/24"
RUN_DIR="${PIVID_RUN_DIR:-/run/pivid}"
HOSTAPD_CONF="${RUN_DIR}/hostapd.conf"
HOSTAPD_CTRL="${RUN_DIR}/hostapd"
# dnsmasq gets the same treatment as hostapd: GENERATED into /run at up() time
# from DNSMASQ_TEMPLATE, with interface= and the addresses substituted. Deriving
# it (rather than shipping a static file with interface=wlan0 baked in) is what
# keeps it from silently desyncing when PIVID_WLAN_IF / PIVID_AP_ADDR are
# overridden -- dnsmasq would bind the wrong interface and the captive portal
# would answer nobody. The unit reads $DNSMASQ_CONF, never the template.
DNSMASQ_CONF="${RUN_DIR}/dnsmasq.conf"
# Deployed location first; fall back to the copy sitting next to this script so
# the host test (and a from-checkout run) works without an install step.
if [ -n "${PIVID_DNSMASQ_TEMPLATE:-}" ]; then
    DNSMASQ_TEMPLATE="$PIVID_DNSMASQ_TEMPLATE"
elif [ -r /opt/pivid/dnsmasq.conf.in ]; then
    DNSMASQ_TEMPLATE=/opt/pivid/dnsmasq.conf.in
else
    DNSMASQ_TEMPLATE="$(cd "$(dirname "$0")" && pwd)/dnsmasq.conf.in"
fi
HOSTAPD_UNIT="${PIVID_HOSTAPD_UNIT:-pivid-config-hostapd.service}"
DNSMASQ_UNIT="${PIVID_DNSMASQ_UNIT:-pivid-config-dnsmasq.service}"
# The boot/hotplug WiFi client is ifup@wlan0.service (DietPi ifupdown +
# allow-hotplug wlan0): re-fired by any wlan0 add/remove udev event, so it will
# re-grab the radio from the AP unless stopped AND masked while config mode runs.
IFUP_UNIT="ifup@${WLAN_IF}.service"
FLAG="${PIVID_FLAG:-${RUN_DIR}/config-mode}"
AP_PASSWORD="${PIVID_AP_PASSWORD:-}"
# AP bring-up is retried, and each try is confirmed via hostapd's control socket
# reaching state=ENABLED (not merely `systemctl start` returning) -- at early boot
# hostapd can daemonize yet stall before beaconing. Waits are env-overridable so
# the host test runs fast.
AP_RETRIES="${PIVID_AP_RETRIES:-3}"
AP_WAIT_TRIES="${PIVID_AP_WAIT_TRIES:-10}"
AP_WAIT_SLEEP="${PIVID_AP_WAIT_SLEEP:-0.5}"

# Pull the AP password from the canonical config when not already set via the
# environment (the unit runs without PIVID_AP_PASSWORD exported; tests inject
# PIVID_AP_PASSWORD directly and skip this sourcing step).
PIVID_CONF="${PIVID_CONF:-/opt/pivid/pivid.conf}"
if [ -z "${AP_PASSWORD}" ] && [ -r "${PIVID_CONF}" ]; then
    AP_PASSWORD="$(. "${PIVID_CONF}" 2>/dev/null; printf '%s' "${PIVID_AP_PASSWORD:-}")"
fi

# Role-derived SSID, no suffix (spec decision #9). PIVID_HOSTNAME overrides.
role_ssid() {
    local host="${PIVID_HOSTNAME:-$(hostname)}"
    case "$host" in
        *rx*) echo "PiVid-RX" ;;
        *)    echo "PiVid-TX" ;;
    esac
}

# NB: no country_code / ieee80211d. This is a temporary local config portal on
# fixed channel 6 (2.4 GHz ch 1-11 is universally permitted), and advertising
# 802.11d made hostapd park in COUNTRY_UPDATE waiting on an unsettled regulatory
# domain at early boot -- the AP then never beaconed (HW-confirmed 2026-06-24).
write_hostapd_conf() {
    mkdir -p "$RUN_DIR"
    cat > "$HOSTAPD_CONF" <<EOF
# Generated by pivid-config-net.sh -- open AP for config mode. Do not edit.
interface=${WLAN_IF}
driver=nl80211
ctrl_interface=${HOSTAPD_CTRL}
ssid=$(role_ssid)
hw_mode=g
channel=6
auth_algs=1
wmm_enabled=0
ignore_broadcast_ssid=0
EOF
    # WPA2-PSK if a valid (>=8 char) password is configured; else open AP.
    if [ -n "$AP_PASSWORD" ]; then
        if [ "${#AP_PASSWORD}" -ge 8 ]; then
            cat >> "$HOSTAPD_CONF" <<EOF
wpa=2
wpa_key_mgmt=WPA-PSK
rsn_pairwise=CCMP
wpa_passphrase=${AP_PASSWORD}
EOF
        else
            echo "pivid-config-net: AP password <8 chars; leaving AP open" >&2
        fi
    fi
}

# Render the shipped template into $DNSMASQ_CONF, substituting the interface and
# the AP address. Placeholders (@WLAN_IF@, @AP_ADDR@, @DHCP_LO@, @DHCP_HI@) are
# replaced by shell parameter expansion, not sed, so an address containing sed
# metacharacters cannot corrupt the output.
write_dnsmasq_conf() {
    mkdir -p "$RUN_DIR"
    if [ ! -r "$DNSMASQ_TEMPLATE" ]; then
        echo "pivid-config-net: dnsmasq template $DNSMASQ_TEMPLATE missing" >&2
        return 1
    fi
    # Pool is the .10-.100 host range of whatever /24 AP_ADDR sits in.
    local net="${AP_ADDR%.*}"
    local body
    body="$(cat "$DNSMASQ_TEMPLATE")"
    body="${body//@WLAN_IF@/$WLAN_IF}"
    body="${body//@AP_ADDR@/$AP_ADDR}"
    body="${body//@DHCP_LO@/${net}.10}"
    body="${body//@DHCP_HI@/${net}.100}"
    printf '%s\n' "$body" > "$DNSMASQ_CONF"
}

# True once hostapd's control socket reports the AP actually reached ENABLED
# (beaconing), not merely that `systemctl start` returned / hostapd daemonized.
ap_enabled() {
    hostapd_cli -p "$HOSTAPD_CTRL" -i "$WLAN_IF" status 2>/dev/null \
        | grep -q '^state=ENABLED'
}

up() {
    ap_ok=0

    # 1. Deterministically own the radio. Stop the boot/hotplug client first
    #    (synchronous, so it is gone before hostapd starts), then MASK it so a
    #    wlan0 add/remove udev event cannot respawn it on top of the AP. pkill is
    #    a backstop for a client not tracked by the unit.
    systemctl stop "$IFUP_UNIT" 2>/dev/null || true
    # --runtime: the mask lives in /run (tmpfs), so a power loss while the AP is
    # up cannot strand the client behind a leftover persistent mask -- the next
    # boot starts clean. down() removes it explicitly on a normal exit.
    systemctl mask --runtime "$IFUP_UNIT" 2>/dev/null || true
    pkill -f "wpa_supplicant.*${WLAN_IF}" 2>/dev/null || true
    pkill -f "dhclient.*${WLAN_IF}" 2>/dev/null || true
    ifdown "$WLAN_IF" 2>/dev/null || true

    # Fail-safe: on a signal (e.g. systemd TimeoutStartSec kill) or any non-success
    # exit, run down() -- which UNMASKS ifup@ and restores the client -- so the box
    # is never stranded behind a leftover mask. Disarmed once the AP is confirmed
    # ENABLED, because a successful up() must leave ifup@ masked until down().
    trap 'down; exit 1' INT TERM
    trap '[ "$ap_ok" = 1 ] || down' EXIT

    write_hostapd_conf
    write_dnsmasq_conf

    # 2. AP + captive DHCP/DNS, retried; each try confirmed via ap_enabled().
    local attempt=1
    while [ "$attempt" -le "$AP_RETRIES" ]; do
        ip link set "$WLAN_IF" up        2>/dev/null || true
        ip addr flush dev "$WLAN_IF"     2>/dev/null || true
        ip addr add "$AP_CIDR" dev "$WLAN_IF" 2>/dev/null || true
        if systemctl start "$HOSTAPD_UNIT" && systemctl start "$DNSMASQ_UNIT"; then
            local t=0
            while [ "$t" -lt "$AP_WAIT_TRIES" ]; do
                if ap_enabled; then ap_ok=1; break; fi
                sleep "$AP_WAIT_SLEEP"
                t=$((t + 1))
            done
        fi
        [ "$ap_ok" = 1 ] && break
        echo "pivid-config-net: AP bring-up attempt $attempt/$AP_RETRIES failed; retrying" >&2
        systemctl stop "$DNSMASQ_UNIT" 2>/dev/null || true
        systemctl stop "$HOSTAPD_UNIT" 2>/dev/null || true
        attempt=$((attempt + 1))
    done

    # 3. Roll back to client mode if the AP never enabled (self-stranding guard).
    if [ "$ap_ok" != 1 ]; then
        echo "pivid-config-net: AP failed to enable after $AP_RETRIES attempts; rolling back" >&2
        trap - EXIT INT TERM
        down
        return 1
    fi
    # Success: keep ifup@ masked until down(); disarm the rollback trap.
    trap - EXIT INT TERM
    return 0
}

down() {
    # Clear the config-mode flag FIRST so the LED snaps dark the moment exit
    # begins, rather than rapid-blinking through the multi-second client-restore
    # below (which reads to the operator as "still in config mode" -- observed
    # confusing on hardware 2026-06-15). The unit's ExecStopPost rm is a backstop.
    rm -f "$FLAG" 2>/dev/null || true
    systemctl stop "$DNSMASQ_UNIT" 2>/dev/null || true
    systemctl stop "$HOSTAPD_UNIT" 2>/dev/null || true
    pkill -x hostapd 2>/dev/null || true
    # Robust client restore after AP mode (brcmfmac, hardware-confirmed
    # 2026-06-15): a bare `ifup` is a no-op if ifupdown still thinks wlan0 is up,
    # and fails to re-associate while the NIC is left in AP type. So: ifdown to
    # clear ifupdown state, flush + bounce the link, force the type back to
    # managed, then restore the client.
    ifdown "$WLAN_IF" 2>/dev/null || true
    ip addr flush dev "$WLAN_IF" 2>/dev/null || true
    ip link set "$WLAN_IF" down 2>/dev/null || true
    iw dev "$WLAN_IF" set type managed 2>/dev/null || true
    ip link set "$WLAN_IF" up 2>/dev/null || true
    # Unmask the boot/hotplug client (up() masked it --runtime; the plain unmask
    # is a backstop for any persistent mask from an older build) and restore it
    # via its own unit, so its wpa_supplicant/dhclient live in ifup@'s cgroup --
    # not leaked into config-net's (which caused "left-over process ..." before).
    systemctl unmask --runtime "$IFUP_UNIT" 2>/dev/null || true
    systemctl unmask "$IFUP_UNIT" 2>/dev/null || true
    systemctl start "$IFUP_UNIT" 2>/dev/null || true
}

case "${1:-}" in
    up)   up ;;
    down) down ;;
    *)    echo "usage: $0 up|down" >&2; exit 2 ;;
esac
